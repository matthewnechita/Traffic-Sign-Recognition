# ------------------------------------------------------
# FUNCTION: Gaussian blur and then apply Canny edge detector
# ------------------------------------------------------
def canny_edge(img, ksize=(15,15), low_scale = 0.1, upper_scale = 0.6):
  
    # Blur image to reduce noise
    img_smoothed = cv.GaussianBlur(img, ksize, 0)

    # Canny edge detector
    median_val = np.median(img_smoothed)

    low_th = max(0,low_scale*median_val)
    high_th = min(255,upper_scale*median_val)

    edges = cv.Canny(img_smoothed, low_th, high_th)
    return edges

