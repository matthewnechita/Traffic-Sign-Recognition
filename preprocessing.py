# MAIN FUNCTION: Preprocessing function
# ------------------------------------------------------
def preprocess(img):

    # Resize image
    img = cv.resize(img.copy(), (128,128), interpolation = cv.INTER_CUBIC)
    
    # ---------------------------- CLAHE ----------------------------------------
    # Settings
    kernel_clahe = (5,5)
    cliplimit = 2.0
    gridsize = (4,4)
    
    # HSV CLAHE
    img_hsv_clahe = hsv_clahe(img, ksize=kernel_clahe, clipLimit=cliplimit, tileGridSize=gridsize)
    # ------------------------------------------------------    
    
    # Convert RGB to Gray
    img_hsv2gray_clahe = cv.cvtColor(img_hsv_clahe, cv.COLOR_RGB2GRAY)

    # ---------------------Canny Edge Detection ---------------------------------
    # Settings
    kernel_edge = (15,15)
    low_scale = 0.1
    upper_scale = 0.6
    
    # Canny edge detection
    edges = canny_edge(img_hsv2gray_clahe, ksize=kernel_edge, low_scale=low_scale, upper_scale=upper_scale)
    # ------------------------------------------------------
    
    # Convert to proper shape (128,128,1)
    edges = np.expand_dims(edges, axis=-1)

    combined = np.concatenate([
        #img,                  # (128,128,3)    
        img_hsv_clahe,         # (128,128,3)
        edges                  # (128,128,1)
        ], axis=-1)
    
    return combined/255.0