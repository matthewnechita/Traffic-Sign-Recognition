def draw_bounding_box(img, x1, y1, x2, y2, color=(255,0,0)):
    img_copy = img.copy()
    return cv.rectangle(img_copy, (x1,y1), (x2,y2), color, 4)

# ------------------------------------------------------
# FUNCTION: Cropping image to bounding boxes
# ------------------------------------------------------
def crop_img_to_bounds(img, x1, y1, x2, y2):
    img_copy = img.copy()
    return img_copy[y1:y2, x1:x2]

# ------------------------------------------------------
# FUNCTION: Convert to HSV and do histogram equalization for contrast enhancement
# ------------------------------------------------------
def hsv_hist_eq(img):
    
    # Blur image to reduce noise
    img_blurred = cv.GaussianBlur(img, (5,5), 0)  
    
    # Convert image to HSV
    img_hsv = cv.cvtColor(img_blurred, cv.COLOR_RGB2HSV)
    h, s, v = cv.split(img_hsv)
    
    # Histogram equalization
    v_hist_eq = cv.equalizeHist(v)
    img_hsv_hist_eq = cv.merge((h, s, v_hist_eq))

    # Convert image to RGB
    img_hist_eq = cv.cvtColor(img_hsv_hist_eq, cv.COLOR_HSV2RGB)

    return img_hist_eq

# ------------------------------------------------------
# FUNCTION: Convert to HSV and do CLAHE (contrast limited histogram equalization) for contrast enhancement
# ------------------------------------------------------
def hsv_clahe(img, ksize=(5,5), clipLimit=2.0, tileGridSize=(4,4)):
    
    # Blur image to reduce noise
    img_smoothed = cv.GaussianBlur(img, ksize, 0)  
    
    # Convert image to HSV
    img_hsv = cv.cvtColor(img_smoothed, cv.COLOR_RGB2HSV)
  
    h, s, v = cv.split(img_hsv)

    # CLAHE
    clahe = cv.createCLAHE(clipLimit=clipLimit, tileGridSize=tileGridSize)
    v_clahe = clahe.apply(v)
    img_hsv_clahe = cv.merge((h, s, v_clahe))

    # Convert image to RGB
    img_clahe = cv.cvtColor(img_hsv_clahe, cv.COLOR_HSV2RGB)

    return img_clahe

